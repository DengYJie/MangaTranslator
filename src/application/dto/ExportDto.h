#pragma once

#include "application/error/ApplicationError.h"
#include "domain/model/Uuid.h"

#include <QImage>
#include <QString>
#include <QVector>

namespace manga::application {

enum class ExportFormat {
    Png,
    Jpeg
};

/// Immutable pre-resolved page snapshot; the exporter never reads the project, assets, or UI
/// state. All layers are optional transparent overlays matching the source image geometry.
struct ExportPageSnapshot {
    domain::PageId pageId;
    QString outputStem; // generated by the UseCase from the original project page order
    QImage sourceImage;
    QImage clearLayer;
    QImage translationLayer;
    QImage manualOverrideLayer;
};

struct ExportRequest {
    QVector<ExportPageSnapshot> pages;
    QString outputDir;
    ExportFormat format;
    int jpegQuality{95};
};

struct ExportedPage {
    domain::PageId pageId;
    QString path;
};

struct ExportFailure {
    domain::PageId pageId;
    ApplicationError error;
};

struct ExportResponse {
    QVector<ExportedPage> exported;
    QVector<ExportFailure> failures;
};

} // namespace manga::application
